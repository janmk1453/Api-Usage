// 内置数据覆盖年份（超出范围按「周一至周五 + 峰段」判断，可在设置中补充额外空闲日期）
export const CN_HOLIDAY_DATA_YEARS: number[] = Object.keys(OFF_DAYS_BY_YEAR)
  .map((year) => parseInt(year, 10))
  .sort((a, b) => a - b);

export const CN_HOLIDAY_COVERAGE_LABEL = CN_HOLIDAY_DATA_YEARS.length
  ? `${CN_HOLIDAY_DATA_YEARS[0]}-${CN_HOLIDAY_DATA_YEARS[CN_HOLIDAY_DATA_YEARS.length - 1]}`
  : '无';

const OFF_DAY_SET = new Set<string>();
for (const days of Object.values(OFF_DAYS_BY_YEAR)) {
  for (const day of days) OFF_DAY_SET.add(day);
}

export function isChinaHolidayDate(dayKey: string): boolean {
  return OFF_DAY_SET.has(dayKey);
}

export function hasChinaHolidayData(year: number): boolean {
  return Array.isArray(OFF_DAYS_BY_YEAR[year]);
}
